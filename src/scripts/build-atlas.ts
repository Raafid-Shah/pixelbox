import { BitmapFont, FontStyleName } from "../engine/bitmapfont";

// scripts/build-atlas.ts

export interface GlyphMetric {
  char: string;
  code: number;
  sx: number;
  width: number;
  height: number;
  advance: number;
}

export interface FontAtlasManifest {
  family: string;
  baseSizePx: 8;
  cellSizePx: 10;
  firstCharCode: 32;
  lastCharCode: 126;
  styles: Record<string, number>;
  glyphs: Record<number, GlyphMetric>;
}

const FIRST_CHAR = 32;
const LAST_CHAR = 126;
const CELL_SIZE = 10;

const STYLE_ROWS: readonly FontStyleName[] = [
  'plain',
  'outlined',
  'shadowed',
  'bevel',
  'bevelAmber',
  'scoreRed',
];

/**
 * Pure, synchronous, zero-dependency builder for the 8px font atlas manifest.
 * Works identically in Node.js (Vite buildStart) and in the browser runtime
 * without requiring @types/node.
 */
export function createFontAtlasManifest(): FontAtlasManifest {
  const styles: Record<string, number> = {};
  STYLE_ROWS.forEach((style, idx) => {
    styles[style] = idx * CELL_SIZE;
  });

  const glyphs: Record<number, GlyphMetric> = {};
  for (let code = FIRST_CHAR; code <= LAST_CHAR; code++) {
    const idx = code - FIRST_CHAR;
    glyphs[code] = {
      char: String.fromCharCode(code),
      code,
      sx: idx * CELL_SIZE,
      width: 8,
      height: 8,
      advance: 8,
    };
  }

  return {
    family: 'Press Start 2P',
    baseSizePx: 8,
    cellSizePx: CELL_SIZE,
    firstCharCode: FIRST_CHAR,
    lastCharCode: LAST_CHAR,
    styles,
    glyphs,
  };
}

export const FONT_ATLAS_MANIFEST: FontAtlasManifest = createFontAtlasManifest();

/**
 * Section 16 Step 5: Renders a visual inspection sheet of every ASCII glyph (32..126)
 * across all 6 arcade styles onto the target 320x180 canvas for Phase 0 verification.
 */
export function renderGlyphTestSheet(
  ctx: CanvasRenderingContext2D,
  font: BitmapFont
): void {
  ctx.fillStyle = '#07090f';
  ctx.fillRect(0, 0, 320, 180);

  // Double-line pale-blue HUD border (Section 2 & 3)
  ctx.strokeStyle = '#4f7388';
  ctx.strokeRect(3, 3, 314, 174);
  ctx.strokeStyle = '#8fb8cc';
  ctx.strokeRect(2, 2, 314, 174);

  font.drawText(ctx, 'PIXELBOX V3 FONT ATLAS TEST', 12, 10, {
    style: 'bevelAmber',
    size: 8,
  });

  const sampleLine1 = 'ABCDEFGHIJKLM 0123456789 !@#$%';
  const sampleLine2 = 'nopqrstuvwxyz <>[]{}() +-*/=?:';

  const styles: FontStyleName[] = [
    'bevel',
    'bevelAmber',
    'scoreRed',
    'outlined',
    'shadowed',
    'plain',
  ];

  styles.forEach((style, idx) => {
    const y = 28 + idx * 20;
    font.drawText(ctx, style.toUpperCase().padEnd(10, ' '), 10, y, {
      style: 'plain',
      size: 8,
    });
    font.drawText(ctx, idx % 2 === 0 ? sampleLine1 : sampleLine2, 96, y, {
      style,
      size: 8,
    });
  });

  // Dedicated 16x24 Bevelled Score Red Numeral check at bottom right (Section 5)
  font.drawText(ctx, 'HIGH SCORE:', 12, 154, { style: 'bevel', size: 8 });
  font.drawScoreNumerals(ctx, 18500, 108, 146, 6);
}

/**
 * Emits `src/generated/font-atlas.ts` when running inside Node.js / Vite buildStart
 * without referencing static Node types that would trip a browser-only tsconfig.json.
 */
export async function generateFontAtlasArtifacts(): Promise<FontAtlasManifest> {
  const manifest = createFontAtlasManifest();
  const g = globalThis as Record<string, any>;

  // Safely check if running inside a Node.js environment
  if (g.process && g.process.versions && g.process.versions.node) {
    try {
      const fsModuleName = 'fs';
      const pathModuleName = 'path';
      const fs = await import(/* @vite-ignore */ fsModuleName);
      const path = await import(/* @vite-ignore */ pathModuleName);

      const rootDir: string = g.process.cwd();
      const outDir: string = path.resolve(rootDir, 'src/generated');
      fs.mkdirSync(outDir, { recursive: true });

      const outFile: string = path.join(outDir, 'font-atlas.ts');
      const code = `// AUTO-GENERATED BY scripts/build-atlas.ts — DO NOT EDIT MANUALLY
export const FONT_ATLAS_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;
`;
      fs.writeFileSync(outFile, code, 'utf-8');
    } catch {
      // Ignore file-write in restricted sandbox environments; runtime manifest remains available
    }
  }

  return manifest;
}

/**
 * Section 4: Vite Plugin wrapper that executes generateFontAtlasArtifacts() at buildStart.
 */
export function pixelboxAtlasPlugin() {
  return {
    name: 'pixelbox-font-atlas',
    async buildStart() {
      await generateFontAtlasArtifacts();
    },
  };
}